export const MIN_SOUL_LINK_LEVEL = 220;
// The source data continues to level 2000; levels 1997–2000 cost no Soul Stones.
export const MAX_SOUL_LINK_LEVEL = 2000;

export function getSoulStoneCostForTargetLevel(targetLevel: number) {
  return soulStoneCosts.find((upgrade) => upgrade.lvl === targetLevel)?.amount ?? null;
}

export function getNextSoulStoneUpgrade(currentLevel: number) {
  const upgrade = soulStoneCosts.find((cost) => cost.lvl > currentLevel);
  return upgrade ? { targetLevel: upgrade.lvl, cost: upgrade.amount } : null;
}

export function getSoulStoneUpgradesFrom(currentLevel: number) {
  return soulStoneCosts
    .filter((upgrade) => upgrade.lvl > currentLevel)
    .map((upgrade) => ({ targetLevel: upgrade.lvl, cost: upgrade.amount }));
}

export function getReachableLevelAfterSoulStoneUpgrade(targetLevel: number) {
  return Math.min(targetLevel + 4, MAX_SOUL_LINK_LEVEL);
}

export function canEquipArtifact(role: HeroRole | undefined, artifactId: string): boolean {
  if (!Object.hasOwn(artifactEquipmentRoles, artifactId)) return false;
  const requiredRole = artifactEquipmentRoles[artifactId];
  return requiredRole === null || requiredRole === role;
}
